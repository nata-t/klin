import { importPath, local, type TemplateContext } from "../paths"

/*
 * The frontend: TanStack Query hooks for the five endpoints, a page that
 * lists what the API returns, a form skeleton and the route that shows it.
 */

const q = (s: string) => JSON.stringify(s)

/** "@/features/blog/post/post-page" */
const alias = (path: string) => `@/${importPath("apps/web/src/index.ts", path).slice(2)}`

export function webApiFile({ target: t, command }: TemplateContext) {
  const { one: o, list: l } = t
  const P = o.pascal
  const keys = `${o.camel}Keys`
  const url = `/${t.path}`
  return `import { keepPreviousData, queryOptions, useMutation, useQuery, useQueryClient } from "@tanstack/react-query"
import type { Create${P}Input, ${P}, ${P}List, ${P}ListQuery, Update${P}Input } from "@repo/validators"
import { api } from "@/lib/api-client"

/**
 * /api/${t.path}, as queries and mutations — generated by
 * \`${command}\`.
 *
 * Every key starts with ${q(t.path)}, so one call can refresh all of them, just
 * the lists, or a single ${o.lower}:
 *
 *   queryClient.invalidateQueries({ queryKey: ${keys}.lists() })
 */
export const ${keys} = {
  all: [${q(t.path)}] as const,
  lists: () => [...${keys}.all, "list"] as const,
  list: (query: Partial<${P}ListQuery>) => [...${keys}.lists(), query] as const,
  details: () => [...${keys}.all, "detail"] as const,
  detail: (id: string) => [...${keys}.details(), id] as const,
}

export const ${l.camel}QueryOptions = (query: Partial<${P}ListQuery> = {}) =>
  queryOptions({
    queryKey: ${keys}.list(query),
    queryFn: ({ signal }) => api.get<${P}List>(${q(url)}, query, signal),
    placeholderData: keepPreviousData,
  })

export const ${o.camel}QueryOptions = (id: string) =>
  queryOptions({
    queryKey: ${keys}.detail(id),
    queryFn: ({ signal }) => api.get<${P}>(\`${url}/\${id}\`, undefined, signal),
  })

export function use${l.pascal}(query: Partial<${P}ListQuery> = {}) {
  return useQuery(${l.camel}QueryOptions(query))
}

export function use${P}(id: string) {
  return useQuery(${o.camel}QueryOptions(id))
}

export function useCreate${P}() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: (input: Create${P}Input) => api.post<${P}>(${q(url)}, input),
    onSuccess: () => queryClient.invalidateQueries({ queryKey: ${keys}.lists() }),
    meta: { successMessage: ${q(`${o.title} created`)} },
  })
}

export function useUpdate${P}() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: ({ id, ...input }: Update${P}Input & { id: string }) =>
      api.patch<${P}>(\`${url}/\${id}\`, input),
    onSuccess: (${local(o.camel)}) => {
      queryClient.setQueryData(${keys}.detail(${local(o.camel)}.id), ${local(o.camel)})
      return queryClient.invalidateQueries({ queryKey: ${keys}.lists() })
    },
    meta: { successMessage: ${q(`${o.title} saved`)} },
  })
}

export function useDelete${P}() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: (id: string) => api.delete<{ id: string }>(\`${url}/\${id}\`),
    onSuccess: ({ id }) => {
      queryClient.removeQueries({ queryKey: ${keys}.detail(id) })
      return queryClient.invalidateQueries({ queryKey: ${keys}.lists() })
    },
    meta: { successMessage: ${q(`${o.title} deleted`)} },
  })
}
`
}

export function webFormFile({ target: t }: TemplateContext) {
  const o = t.one
  const P = o.pascal
  const c = local(o.camel)
  const prop = c === o.camel ? c : `${o.camel}: ${c}`
  return `import { type Create${P}Input, create${P}Schema, type ${P} } from "@repo/validators"
import { AppForm, applyServerErrors, useAppForm } from "@/components/form"
import { FieldGroup } from "@/components/ui/field"
import { useCreate${P}, useUpdate${P} } from "./api"

/**
 * Create or edit a ${o.lower}, validated with the schema the API uses — a form
 * that passes here won't be rejected there. Each field in create${P}Schema
 * needs a default value and an input; \`name\` is the example to copy.
 */
export function ${P}Form({ ${prop}, onDone }: { ${o.camel}?: ${P}; onDone?: () => void }) {
  const create${P} = useCreate${P}()
  const update${P} = useUpdate${P}()

  const form = useAppForm({
    defaultValues: {
      // TODO: one default per field
      name: ${c}?.name ?? "",
    } satisfies Create${P}Input as Create${P}Input,
    validators: { onDynamic: create${P}Schema },
    onSubmit: async ({ value }) => {
      try {
        if (${c}) await update${P}.mutateAsync({ id: ${c}.id, ...value })
        else await create${P}.mutateAsync(value)
        onDone?.()
      } catch (error) {
        applyServerErrors(form, error)
      }
    },
  })

  return (
    <AppForm form={form}>
      <FieldGroup>
        {/* TODO: one <form.AppField> per field */}
        <form.AppField name="name">
          {(field) => <field.TextField label="Name" autoFocus />}
        </form.AppField>
        <form.AppForm>
          <form.SubmitButton className="self-end">{${c} ? "Save changes" : ${q(`Create ${o.lower}`)}}</form.SubmitButton>
        </form.AppForm>
      </FieldGroup>
    </AppForm>
  )
}
`
}

export function webPageFile({ target: t, command }: TemplateContext) {
  const { one: o, many: m, list: l, leaf: L } = t
  return `import { PlusIcon } from "lucide-react"
import { useState } from "react"
import { PageHeader } from "@/components/page-header"
import { Button } from "@/components/ui/button"
import { Card, CardContent } from "@/components/ui/card"
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogTrigger } from "@/components/ui/dialog"
import { Skeleton } from "@/components/ui/skeleton"
import { use${l.pascal} } from "./api"
import { ${o.pascal}Form } from "./${o.kebab}-form"

/**
 * /${t.path} — generated by \`${command}\`.
 * A starting point: it lists what the API returns and creates new ones.
 */
export function ${L.pascal}Page() {
  const [creating, setCreating] = useState(false)
  const { data, isPending } = use${l.pascal}()

  return (
    <>
      <PageHeader
        title=${q(m.title)}
        description="TODO: what this page is for."
        actions={
          <Dialog open={creating} onOpenChange={setCreating}>
            <DialogTrigger render={<Button />}>
              <PlusIcon /> New ${o.lower}
            </DialogTrigger>
            <DialogContent>
              <DialogHeader>
                <DialogTitle>New ${o.lower}</DialogTitle>
              </DialogHeader>
              <${o.pascal}Form onDone={() => setCreating(false)} />
            </DialogContent>
          </Dialog>
        }
      />

      <Card>
        <CardContent>
          {isPending ? (
            <Skeleton className="h-24" />
          ) : !data?.items.length ? (
            <p className="text-sm text-muted-foreground">No ${m.lower} yet.</p>
          ) : (
            <ul className="divide-y">
              {data.items.map((item) => (
                // TODO: show the fields that matter
                <li key={item.id} className="py-3 text-sm">
                  {item.name}
                </li>
              ))}
            </ul>
          )}
        </CardContent>
      </Card>
    </>
  )
}
`
}

export function webRouteFile({ target: t, paths }: TemplateContext) {
  return `import { createFileRoute } from "@tanstack/react-router"
import { ${t.list.camel}QueryOptions } from "${alias(paths.web.api)}"
import { ${t.leaf.pascal}Page } from "${alias(paths.web.page)}"

export const Route = createFileRoute(${q(`/_app/${t.path}`)})({
  staticData: { title: ${q(t.many.title)} },
  // Prefetch on navigation (and on link hover) so the page renders with data.
  loader: ({ context }) => context.queryClient.ensureQueryData(${t.list.camel}QueryOptions()),
  component: ${t.leaf.pascal}Page,
})
`
}

/** A Lucide icon that fits common names, for the sidebar entry. */
export function iconFor(name: string) {
  const table: Array<[RegExp, string]> = [
    [/project|board|workspace/, "FolderKanbanIcon"],
    [/task|todo|issue|ticket/, "ListTodoIcon"],
    [/invoice|bill|payment|receipt|expense|loan/, "ReceiptIcon"],
    [/customer|client|contact|member|person|people|user|employee|team/, "UsersIcon"],
    [/product|item|inventory|package/, "PackageIcon"],
    [/order|cart|purchase/, "ShoppingCartIcon"],
    [/post|article|blog|story|news/, "NewspaperIcon"],
    [/event|meeting|booking|appointment|calendar/, "CalendarIcon"],
    [/comment|message|chat|feedback|review/, "MessageSquareIcon"],
    [/file|document|doc|report/, "FileTextIcon"],
    [/note|memo/, "StickyNoteIcon"],
    [/tag|label|category/, "TagIcon"],
    [/location|place|address|venue/, "MapPinIcon"],
  ]
  return table.find(([pattern]) => pattern.test(name))?.[1] ?? "BoxIcon"
}

/** Mirrors the template's packages-ui rewrite: `@/components/ui/x` → `@repo/ui/components/x`. */
export function toUiPackageImports(code: string) {
  return code
    .replaceAll('"@/components/ui/', '"@repo/ui/components/')
    .replaceAll('"@/lib/utils"', '"@repo/ui/lib/utils"')
    .replaceAll('"@/hooks/use-mobile"', '"@repo/ui/hooks/use-mobile"')
}
