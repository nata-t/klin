import { importPath, type TemplateContext } from "../paths"
import type { Target } from "../target"

/** Every name the schema file exports — the other layers import these. */
export function schemaExports({ one: o }: Target) {
  return [
    `create${o.pascal}Schema`,
    `update${o.pascal}Schema`,
    `${o.camel}ListQuerySchema`,
    `${o.camel}Schema`,
    `${o.camel}ListSchema`,
    o.pascal,
    `${o.pascal}List`,
    `Create${o.pascal}Input`,
    `Create${o.pascal}`,
    `Update${o.pascal}Input`,
    `Update${o.pascal}`,
    `${o.pascal}ListQueryInput`,
    `${o.pascal}ListQuery`,
  ]
}

/* ─── packages/validators ──────────────────────────────────────────────── */

export function validatorsFile({ target: t, paths, command }: TemplateContext) {
  const o = t.one
  const from = (file: string) => importPath(paths.validators, `packages/validators/src/${file}`)
  return `import { z } from "zod"
import { listQuerySchema, paginatedSchema } from "${from("api.ts")}"
import { idSchema, isoDate } from "${from("common.ts")}"

/**
 * ${o.title} — the shapes the API and the web app share. Generated by
 * \`${command}\`.
 *
 * \`name\` is an example: rename it, and put your fields next to it — in
 * \`${o.camel}Fields\` (what clients send) and \`${o.camel}Schema\` (what the API
 * returns). The API's validation, the web form and every type below follow.
 */

const ${o.camel}Fields = {
  // TODO: your fields
  name: z.string().trim().min(1, "Name is required").max(120, "Keep it under 120 characters"),
}

/* ─── Requests ───────────────────────────────────────────────────────────── */

export const create${o.pascal}Schema = z.object({
  ...${o.camel}Fields,
})

/** PATCH semantics: every field optional, no defaults (omitted = unchanged). */
export const update${o.pascal}Schema = z.object(${o.camel}Fields).partial()

/** page, limit, search and sortOrder come from listQuerySchema. */
export const ${o.camel}ListQuerySchema = listQuerySchema.extend({
  sortBy: z.enum(["createdAt", "updatedAt"]).default("createdAt"),
})

/* ─── Responses ──────────────────────────────────────────────────────────── */

/** What the API sends back. Fields left out here never leave the API. */
export const ${o.camel}Schema = z.object({
  id: idSchema,
  // TODO: the fields the API returns
  name: z.string(),
  createdAt: isoDate(),
  updatedAt: isoDate(),
})

export const ${o.camel}ListSchema = paginatedSchema(${o.camel}Schema)

/* ─── Types ──────────────────────────────────────────────────────────────── */

export type ${o.pascal} = z.infer<typeof ${o.camel}Schema>
export type ${o.pascal}List = z.infer<typeof ${o.camel}ListSchema>
export type Create${o.pascal}Input = z.input<typeof create${o.pascal}Schema>
export type Create${o.pascal} = z.infer<typeof create${o.pascal}Schema>
export type Update${o.pascal}Input = z.input<typeof update${o.pascal}Schema>
export type Update${o.pascal} = z.infer<typeof update${o.pascal}Schema>
export type ${o.pascal}ListQueryInput = z.input<typeof ${o.camel}ListQuerySchema>
export type ${o.pascal}ListQuery = z.infer<typeof ${o.camel}ListQuerySchema>
`
}

/* ─── packages/db ──────────────────────────────────────────────────────── */

export function prismaFile({ target: t, command }: TemplateContext, migrate: string) {
  const o = t.one
  return `// ${o.title} — generated by \`${command}\`.
// \`name\` is an example: add your columns, then \`${migrate}\`
// (creates and applies a migration).
model ${o.pascal} {
  id        String   @id @default(cuid())
  // TODO: your columns
  name      String
  // Owned by a user? Add the relation, and \`${t.list.camel} ${o.pascal}[]\` to the User model:
  // userId    String
  // user      User     @relation(fields: [userId], references: [id], onDelete: Cascade)
  createdAt DateTime @default(now())
  updatedAt DateTime @updatedAt

  @@map("${o.snake}")
}
`
}
