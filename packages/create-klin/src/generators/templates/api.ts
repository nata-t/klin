export function nestControllerFile({ target: t, command }: TemplateContext) {
  const { one: o, leaf: L } = t
  const service = t.list.camel
  return `import { Body, Controller, Delete, Get, Param, Patch, Post, Query } from "@nestjs/common"
import { ZodSerializerDto } from "nestjs-zod"
import {
  Create${o.pascal}Dto,
  ${o.pascal}Dto,
  ${o.pascal}ListDto,
  ${o.pascal}ListQueryDto,
  Update${o.pascal}Dto,
} from "./${L.kebab}.dto"
import { ${L.pascal}Service } from "./${L.kebab}.service"

/**
 * /api/${t.path} — generated by \`${command}\`.
 *
 * Every route needs a signed-in user (the global AuthGuard): mark one
 * @Public() to open it up, or read the user with @CurrentUser() — both come
 * from src/common.
 */
@Controller(${q(t.path)})
export class ${L.pascal}Controller {
  constructor(private readonly ${service}: ${L.pascal}Service) {}

  @Get()
  @ZodSerializerDto(${o.pascal}ListDto)
  list(@Query() query: ${o.pascal}ListQueryDto) {
    return this.${service}.list(query)
  }

  @Get(":id")
  @ZodSerializerDto(${o.pascal}Dto)
  get(@Param("id") id: string) {
    return this.${service}.get(id)
  }

  @Post()
  @ZodSerializerDto(${o.pascal}Dto)
  create(@Body() input: Create${o.pascal}Dto) {
    return this.${service}.create(input)
  }

  @Patch(":id")
  @ZodSerializerDto(${o.pascal}Dto)
  update(@Param("id") id: string, @Body() input: Update${o.pascal}Dto) {
    return this.${service}.update(id, input)
  }

  @Delete(":id")
  remove(@Param("id") id: string) {
    return this.${service}.remove(id)
  }
}
`
}

