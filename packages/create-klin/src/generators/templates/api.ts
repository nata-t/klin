export function expressRoutesFile(ctx: TemplateContext) {
  const { target: t, paths, command } = ctx
  const o = t.one
  const fn = plainFunctions(t)
  const ns = t.list.camel
  const router = `${t.leaf.camel}Router`
  const v = local(o.camel)
  const from = (file: string) => importPath(paths.plain.routes, `apps/api/src/${file}`)
  return `${schemaImports(t)}
import { Router } from "express"
import { ok } from "${from("lib/http.ts")}"
import { requireAuth } from "${from("middleware/auth.ts")}"
import * as ${ns} from "${importPath(paths.plain.routes, paths.plain.service)}"

/**
 * /api/${t.path} — generated by \`${command}\`.
 *
 * Signed-in users only. \`schema.parse()\` validates the input (a ZodError
 * becomes a 422 with per-field details); parsing the result through the
 * response schema keeps unlisted fields out and turns dates into ISO strings.
 */
export const ${router} = Router()
${router}.use(requireAuth)

${router}.get("/", async (req, res) => {
  const query = ${o.camel}ListQuerySchema.parse(req.query)
  const list = await ${ns}.${fn.list}(query)
  res.json(ok(req, ${o.camel}ListSchema.parse(list)))
})

${router}.get("/:id", async (req, res) => {
  const ${v} = await ${ns}.${fn.get}(idSchema.parse(req.params.id))
  res.json(ok(req, ${o.camel}Schema.parse(${v})))
})

${router}.post("/", async (req, res) => {
  const input = create${o.pascal}Schema.parse(req.body)
  const ${v} = await ${ns}.${fn.create}(input)
  res.status(201).json(ok(req, ${o.camel}Schema.parse(${v})))
})

${router}.patch("/:id", async (req, res) => {
  const input = update${o.pascal}Schema.parse(req.body)
  const ${v} = await ${ns}.${fn.update}(idSchema.parse(req.params.id), input)
  res.json(ok(req, ${o.camel}Schema.parse(${v})))
})

${router}.delete("/:id", async (req, res) => {
  res.json(ok(req, await ${ns}.${fn.remove}(idSchema.parse(req.params.id))))
})
`
}

export function fastifyRoutesFile(ctx: TemplateContext) {
  const { target: t, paths, command } = ctx
  const o = t.one
  const fn = plainFunctions(t)
  const ns = t.list.camel
  const v = local(o.camel)
  const from = (file: string) => importPath(paths.plain.routes, `apps/api/src/${file}`)
  return `${schemaImports(t)}
import { z } from "zod"
import { requireAuth } from "${from("hooks/auth.ts")}"
import { ok } from "${from("lib/http.ts")}"
import type { ZodPlugin } from "${from("lib/zod.ts")}"
import * as ${ns} from "${importPath(paths.plain.routes, paths.plain.service)}"

const params = z.object({ id: idSchema })

/**
 * /api/${t.path} — generated by \`${command}\`.
 *
 * Signed-in users only. Fastify validates body, query and params with the
 * route schemas (a failure becomes a 422 with per-field details) and types
 * \`request.body\` & co. from them; results are parsed through the response
 * schema, which keeps unlisted fields out and turns dates into ISO strings.
 */
export const ${t.leaf.camel}Routes: ZodPlugin = async (app) => {
  app.addHook("preHandler", requireAuth)

  app.get("/", { schema: { querystring: ${o.camel}ListQuerySchema } }, async (request) => {
    const list = await ${ns}.${fn.list}(request.query)
    return ok(request, ${o.camel}ListSchema.parse(list))
  })

  app.get("/:id", { schema: { params } }, async (request) => {
    const ${v} = await ${ns}.${fn.get}(request.params.id)
    return ok(request, ${o.camel}Schema.parse(${v}))
  })

  app.post("/", { schema: { body: create${o.pascal}Schema } }, async (request, reply) => {
    const ${v} = await ${ns}.${fn.create}(request.body)
    return reply.code(201).send(ok(request, ${o.camel}Schema.parse(${v})))
  })

  app.patch("/:id", { schema: { params, body: update${o.pascal}Schema } }, async (request) => {
    const ${v} = await ${ns}.${fn.update}(request.params.id, request.body)
    return ok(request, ${o.camel}Schema.parse(${v}))
  })

  app.delete("/:id", { schema: { params } }, async (request) => {
    return ok(request, await ${ns}.${fn.remove}(request.params.id))
  })
}
`
}
