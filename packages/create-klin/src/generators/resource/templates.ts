/*
 * Every file `klin generate resource` writes. They mirror the hand-written
 * Notes example in the template, so generated code reads like the rest of
 * the project.
 */

const q = (s: string) => JSON.stringify(s)
const indent = (lines: string[], n = 2) => lines.map((l) => (l ? " ".repeat(n) + l : l)).join("\n")

/* ─── packages/validators ──────────────────────────────────────────────── */

export function validatorsFile({ names: n, fields }: ResourceSpec) {
  const helpers = new Set(["idSchema", "isoDate"])
  const optionalText = fields.some((f) => f.optional && ["string", "text", "date", "datetime"].includes(f.type))
  if (optionalText) {
    helpers.add("emptyToUndefined")
    helpers.add("emptyToNull")
  }
  const sortable = ["createdAt", "updatedAt", ...fields.filter((f) => f.type !== "boolean" && f.type !== "text").map((f) => f.name)]
  const booleans = fields.filter((f) => f.type === "boolean")

  return `import { z } from "zod"
import { listQuerySchema, paginatedSchema } from "./api"
import { ${[...helpers].sort().join(", ")} } from "./common"

/**
 * ${n.plural.title} — generated by \`klin generate resource ${n.kebab}\`.
 *
 * These schemas validate API requests, shape API responses and validate the
 * web forms. Edit the rules here and both sides follow.
 */

const ${n.camel}Fields = {
${indent(fields.map((f) => `${f.name}: ${zodCreate(f)},`))}
}

/* ─── Requests ───────────────────────────────────────────────────────────── */

export const create${n.pascal}Schema = z.object({
  ...${n.camel}Fields,${booleans.map((f) => `\n  ${f.name}: ${n.camel}Fields.${f.name}.default(false),`).join("")}
})

/** PATCH semantics: every field optional, no defaults (omitted = unchanged). */
export const update${n.pascal}Schema = z
  .object({
${indent(fields.map((f) => `${f.name}: ${zodUpdate(f)},`), 4)}
  })
  .partial()

export const ${n.camel}ListQuerySchema = listQuerySchema.extend({
  sortBy: z.enum([${sortable.map(q).join(", ")}]).default("createdAt"),
})

/* ─── Responses ──────────────────────────────────────────────────────────── */

export const ${n.camel}Schema = z.object({
  id: idSchema,
${indent(fields.map((f) => `${f.name}: ${zodWire(f)},`))}
  createdAt: isoDate(),
  updatedAt: isoDate(),
})

export const ${n.camel}ListSchema = paginatedSchema(${n.camel}Schema)

/* ─── Types ──────────────────────────────────────────────────────────────── */

export type ${n.pascal} = z.infer<typeof ${n.camel}Schema>
export type ${n.pascal}List = z.infer<typeof ${n.camel}ListSchema>
export type Create${n.pascal}Input = z.input<typeof create${n.pascal}Schema>
export type Create${n.pascal} = z.infer<typeof create${n.pascal}Schema>
export type Update${n.pascal}Input = z.input<typeof update${n.pascal}Schema>
export type Update${n.pascal} = z.infer<typeof update${n.pascal}Schema>
export type ${n.pascal}ListQueryInput = z.input<typeof ${n.camel}ListQuerySchema>
export type ${n.pascal}ListQuery = z.infer<typeof ${n.camel}ListQuerySchema>
`
}

/* ─── packages/db ──────────────────────────────────────────────────────── */

export function prismaFile({ names: n, fields, scope, database }: ResourceSpec) {
  const rows: Array<[string, string]> = [["id", "String   @id @default(cuid())"]]
  for (const field of fields) rows.push([field.name, prismaType(field, database)])
  if (scope === "user") {
    rows.push(["userId", "String"])
    rows.push(["user", "User     @relation(fields: [userId], references: [id], onDelete: Cascade)"])
  } else if (scope === "org") {
    rows.push(["organizationId", "String"])
    rows.push(["organization", "Organization @relation(fields: [organizationId], references: [id], onDelete: Cascade)"])
  }
  rows.push(["createdAt", "DateTime @default(now())"])
  rows.push(["updatedAt", "DateTime @updatedAt"])
  const width = Math.max(...rows.map(([name]) => name.length)) + 1
  const index = scope === "user" ? "\n  @@index([userId])" : scope === "org" ? "\n  @@index([organizationId])" : ""

  return `// ${n.plural.title} — generated by \`klin generate resource ${n.kebab}\`.
// After editing: \`pnpm db:migrate\` (creates and applies a migration).
model ${n.pascal} {
${rows.map(([name, type]) => `  ${name.padEnd(width)}${type}`).join("\n")}
${index}
  @@map(${q(n.snake)})
}
`
}

